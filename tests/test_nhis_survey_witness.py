@pytest.mark.parametrize(
    "diagnosis,kind", [(1, "2"), (True, "2"), ("1", 2), ("1", None), ("secret", "2"), ("1", "\t")]
)
def test_invalid_native_categories_are_sanitized(diagnosis, kind):
    frame, domains = fixture()
    frame["DIBEV_A"] = pd.Series([diagnosis] * len(frame), index=frame.index)
    frame["DIBTYPE_A"] = pd.Series([kind] * len(frame), index=frame.index)
    with pytest.raises(ValueError) as failure:
        assess(frame, domains)
    assert "secret" not in str(failure.value)
    assert failure.value.__cause__ is None


@pytest.mark.parametrize(
    "case",
    [
        "missing_field",
        "duplicate_field",
        "duplicate_index",
        "missing_index",
        "empty",
        "domain_order",
        "nonboolean",
        "missing_domain",
        "duplicate_domain",
        "no_domain",
        "not_frame",
        "not_domains",
    ],
)
def test_invalid_shapes_refuse(case):
    frame, domains = fixture()
    if case == "missing_field":
        frame = frame.drop(columns="DIBEV_A")
    elif case == "duplicate_field":
        frame = pd.concat([frame, frame[["DIBEV_A"]]], axis=1)
    elif case == "duplicate_index":
        frame.index = [1] * len(frame)
    elif case == "missing_index":
        frame.index = [None] + list(range(7))
    elif case == "empty":
        frame, domains = frame.iloc[:0], domains.iloc[:0]
    elif case == "domain_order":
        domains = domains.iloc[::-1]
    elif case == "nonboolean":
        domains = domains.astype(int)
    elif case == "missing_domain":
        domains = domains.astype("boolean")
        domains.iloc[0, 0] = pd.NA
    elif case == "duplicate_domain":
        domains = pd.concat([domains, domains[["all"]]], axis=1)
    elif case == "no_domain":
        domains = domains.iloc[:, :0]
    elif case == "not_frame":
        frame = []
    else:
        domains = []
    with pytest.raises(ValueError):
        assess(frame, domains)
